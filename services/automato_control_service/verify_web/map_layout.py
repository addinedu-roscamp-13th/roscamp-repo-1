#!/usr/bin/env python3
"""검증 웹 — 맵 배경(재배 베드·로봇팔). 화면에서 '여기가 어디인지' 알아보게 하는 용도.

왜 이 파일이 따로 있나:
  재배 베드와 로봇팔은 DB 에 없는 정보다. DB 에는 로봇이 지나다니는 '그래프'
  (waypoints/corridors)와 시설 지점(task_points)만 있고, 온실 구조물은 들어있지 않다.
  반면 충전소·수확대·예냉실은 이제 task_points 가 waypoint_id 를 갖게 되어
  **DB 좌표에서 그대로 유도한다**(server.py 의 _SELECT_TASK_POINTS) — 여기 없다.
  즉 이 파일에는 'DB 가 모르는 것'만 남는다.

좌표계 — 도면의 cm 치수를 그대로 옮기지 '않는' 이유:
  DB 좌표는 로봇이 실제로 찍은 실측값이고, 손도면은 설계 의도다. 둘은 어긋난다.
  그래서 구조물은 '도면의 배치와 비율'만 참고해 실측 노드 좌표에 맞춰 놓는다.
  노드·통로만 진짜다.

단위는 m (waypoints.x_coord/y_coord 와 동일). 화면 변환은 프런트(app.js)가 한다.
"""

# 방 외곽(벽). 노드 전체(x -0.013~0.778, y -0.425~0.886)를 여유 있게 감싼다.
# 위아래로 특히 넉넉히 잡은 이유: 시설(충전소·수확대·예냉실) 박스를 노드에서 20~30cm
# 바깥의 '고정된 행'에 수평으로 그리기 때문이다(위 행 y≈-0.69, 아래 행 y≈1.11).
# 이 바깥 행까지 방 안에 들어와야 하므로 y0/y1 을 시설 행보다 더 바깥으로 잡는다.
ROOM = {"x0": -0.12, "y0": -0.73, "x1": 0.85, "y1": 1.15}

# 구조물. kind 는 화면에서 색·질감을 고르는 데 쓴다.
#   bed : 방울토마토 재배 베드  /  arm : 로봇팔(Ddagi) 설치 위치
#
# 배치 근거(화면 기준 — DB x 가 클수록 왼쪽, y 가 클수록 아래):
#   · 아래쪽 노드 열은 x ≈ 0.72(A) / 0.33(C) / 0.00(D) 세 줄이다.
#     세로 베드 2개는 A~C 사이, C~D 사이의 '빈 구간'에 정확히 들어간다.
#   · 위쪽 가로 베드는 1·2 행(y≈-0.41)과 5·6·8 행(y≈0.00) 사이를 막는다.
STRUCTURES = [
    # ── 로봇팔 2대 ── 위쪽 벽의 '양쪽 끝'에 선다.
    # 원래 이 벽이 위쪽 구역을 통째로 막고 있었고 그 위에 로봇팔이 있었다. 벽의 '가운데'를
    # 뚫어 수확대(wp20·21)가 그 구멍으로 올라왔고, 양 끝은 계속 벽이라 로봇팔이 그대로 남는다.
    # 그래서 로봇팔은 가운데(수확대 자리)를 비우고 좌우 끝에 배치한다.
    #   화면 왼쪽 끝 = DB x 큰 쪽(wp1 x≈0.70 위) / 화면 오른쪽 끝 = DB x 작은 쪽(wp3 x≈0.02 위).
    #   (화면 x 는 DB x 의 반대 방향이라 DB x 가 클수록 왼쪽이다.)
    # y 는 -0.69~-0.585 — 수확대(app.js 의 TOP_FAR=-0.69)와 '같은 줄'에 맞춰
    # 로봇팔-수확대-수확대-로봇팔이 수평이 되게 한다. 맨 윗줄 통로(y≈-0.41)보다 위라 안 건드린다.
    {"kind": "arm", "label": "로봇팔", "x0": 0.62, "y0": -0.69, "x1": 0.80, "y1": -0.585},
    {"kind": "arm", "label": "로봇팔", "x0": -0.06, "y0": -0.69, "x1": 0.12, "y1": -0.585},

    # ── 가로 베드 ── '통짜'인 이유(중요):
    #   예전 시드에는 1-5, 2-6 통로가 있어서 베드를 쪼개 길을 내줬었다. 그런데 실제 현장은
    #   이 베드가 1·2 행과 4~8 행 사이를 막고 있어 그 통로가 존재할 수 없고, 시드에서도
    #   삭제됐다. 그래서 지금은 쪼갤 이유가 없다 — 있는 그대로 한 덩어리로 그린다.
    #   단 x < 0.08 구간은 비워야 한다. 통로 3-8(x≈0.03)이 그 옆 아일로 지나가고,
    #   위쪽 줄(1·2·3)로 들어가는 유일한 진입로이기 때문이다.
    {"kind": "bed", "label": "토마토 베드", "x0": 0.09, "y0": -0.37, "x1": 0.76, "y1": -0.10},

    # ── 세로 베드 2개 ── 노드 열 사이 빈 구간(통로를 건드리지 않는다)
    {"kind": "bed", "label": "토마토 베드", "x0": 0.42, "y0": 0.10, "x1": 0.64, "y1": 0.64},
    {"kind": "bed", "label": "토마토 베드", "x0": 0.07, "y0": 0.10, "x1": 0.27, "y1": 0.64},
]


def get_layout() -> dict:
    """배경 레이아웃(방 외곽 + 구조물)을 프런트가 쓰기 좋은 형태로 돌려준다."""
    return {"room": ROOM, "structures": STRUCTURES}
